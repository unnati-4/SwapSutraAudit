/**
 * Writes legal/partner-agreement-<type>.md from src/data/partnerContracts.ts
 * and embeds the same text in appsscript.js (PARTNER_AGREEMENT_TEXT), which
 * the script uses for the signed copy it emails and saves to Drive.
 *
 *   node scripts/gen-partner-agreements.cjs
 *
 * Run it after any change to the agreements. tests/test_partners.cjs checks
 * the three stay identical.
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const ts = require(path.join(root, 'node_modules', 'typescript'));
const src = fs.readFileSync(path.join(root, 'src/data/partnerContracts.ts'), 'utf8');
const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const m = { exports: {} };
new Function('require', 'module', 'exports', out)(require, m, m.exports);
const text = {};
for (const [t, c] of Object.entries(m.exports.PARTNER_CONTRACTS)) {
  const md = m.exports.contractMarkdown(c);
  fs.writeFileSync(path.join(root, 'legal', `partner-agreement-${t}.md`), md);
  text[t] = md;
}
const gsPath = path.join(root, 'appsscript.js');
const gs = fs.readFileSync(gsPath, 'utf8');
const START = '// <partner-agreements> generated by scripts/gen-partner-agreements.cjs — do not edit by hand';
const END = '// </partner-agreements>';
const block = START + '\nconst PARTNER_AGREEMENT_TEXT = ' + JSON.stringify(text) + ';\n' + END;
const a = gs.indexOf(START), b = gs.indexOf(END);
const next = a !== -1 && b !== -1 ? gs.slice(0, a) + block + gs.slice(b + END.length) : gs.replace(/\s*$/, '\n\n' + block + '\n');
fs.writeFileSync(gsPath, next);
console.log('agreements written and embedded:', Object.keys(text).join(', '));
